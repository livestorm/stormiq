          Try a different search term or
          <button type="button" class="ghost-link-button" @click="clearFilters">clear the filters</button>.
        </p>
      </section>

      <!-- Grid view: current card layout. -->
      <div v-else-if="viewMode === 'grid'" class="single-analysis-grid">
        <article
          v-for="card in displayedSessions"
          :key="card.sessionId"
          class="single-analysis-card"
          tabindex="0"
          role="button"
          :aria-label="`Open ${cardTitle(card)}`"
          @click="openSession(card.sessionId)"
          @keydown.enter="openSession(card.sessionId)"
          @keydown.space.prevent="openSession(card.sessionId)"
        >
          <div class="single-analysis-card-cover" :style="{ background: gradientFor(card.sessionId) }">
            <img
              v-if="card.hasCoverImage"
              class="single-analysis-card-cover-image"
              :src="coverImageUrl(card)"
              :alt="`Cover image for ${cardTitle(card)}`"
              loading="lazy"
            />
            <span v-else class="single-analysis-card-initials">{{ initialsFor(cardTitle(card)) }}</span>
          </div>
          <div class="single-analysis-card-body">
            <h3 class="single-analysis-card-title">{{ cardTitle(card) }}</h3>
            <p class="single-analysis-card-meta">
              <span>{{ formattedDate(card) }}</span>
              <span v-if="card.durationLabel"> · {{ card.durationLabel }}</span>
              <span v-if="card.attendeesCount != null"> · {{ card.attendeesCount }} attendees</span>
            </p>
            <p class="single-analysis-card-generator">{{ generatedByLine(card) }}</p>
          </div>
        </article>
      </div>

      <!-- List view: horizontal rows, denser. -->
      <div v-else class="single-analysis-list">
        <article
