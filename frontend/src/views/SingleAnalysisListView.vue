            />
            <span v-else class="single-analysis-row-initials">{{ initialsFor(cardTitle(card)) }}</span>
          </div>
          <div class="single-analysis-row-body">
            <h3 class="single-analysis-row-title">{{ cardTitle(card) }}</h3>
            <p class="single-analysis-row-meta">
              <span>{{ formattedDate(card) }}</span>
              <span v-if="card.durationLabel"> · {{ card.durationLabel }}</span>
              <span v-if="card.attendeesCount != null"> · {{ card.attendeesCount }} attendees</span>
