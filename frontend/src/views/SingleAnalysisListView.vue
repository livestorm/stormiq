<script setup>
import { computed, onMounted, ref, watch } from "vue";
import { useRouter } from "vue-router";
import { useWorkspace } from "../store/workspace";

const { state, loadWorkspaceSessions } = useWorkspace();
const router = useRouter();

function maybeLoad() {
  // Only fire when we actually have an auth context. Without it,
  // loadWorkspaceSessions short-circuits to an empty list without
  // touching the server, and we'd never re-trigger when auth lands.
  if (!state.auth.connectedUser && !state.auth.allowLocalApiKeyFallback) {
    return;
  }
  if (!state.workspaceSessions.length || isStale.value) {
    loadWorkspaceSessions().catch(() => {});
  }
}

onMounted(maybeLoad);

watch(
  () => [state.auth.connectedUser, state.auth.allowLocalApiKeyFallback],
  () => maybeLoad(),
);

const STALE_AFTER_MS = 60 * 1000;
const isStale = computed(
  () => Date.now() - (state.workspaceSessionsLoadedAt || 0) > STALE_AFTER_MS,
);

const isLoadingFirstTime = computed(
  () => state.loading.workspaceSessions && !state.workspaceSessions.length,
);

const sessions = computed(() => state.workspaceSessions || []);
const hasAnySessions = computed(() => sessions.value.length > 0);
const isConnected = computed(
  () => Boolean(state.auth?.connectedUser || state.auth?.allowLocalApiKeyFallback),
);

// ── View mode (grid / list), persisted in localStorage ─────────────────────
const VIEW_MODE_STORAGE_KEY = "stormiq:single-analysis:viewMode";
const viewMode = ref(loadViewMode());

function loadViewMode() {
  try {
    const value = String(window.localStorage.getItem(VIEW_MODE_STORAGE_KEY) || "").trim();
    return value === "list" ? "list" : "grid";
  } catch (_) {
    return "grid";
  }
}

watch(viewMode, (next) => {
  try {
    window.localStorage.setItem(VIEW_MODE_STORAGE_KEY, next);
  } catch (_) {
    // Ignore localStorage failures (private browsing, etc.) — the
    // chosen mode is still honoured for the rest of the session.
  }
});

// ── Search / filter / sort state ───────────────────────────────────────────
const searchQuery = ref("");
const eventFilter = ref(""); // "" = all events; otherwise an event_id
const sortBy = ref("generatedDesc"); // see SORT_OPTIONS below

const SORT_OPTIONS = [
  { value: "generatedDesc", label: "Newest (added)" },
  { value: "generatedAsc", label: "Oldest (added)" },
  { value: "sessionDateDesc", label: "Session date (newest first)" },
  { value: "sessionDateAsc", label: "Session date (oldest first)" },
  { value: "eventAsc", label: "Event title (A→Z)" },
  { value: "eventDesc", label: "Event title (Z→A)" },
  { value: "generatorAsc", label: "Generated by (A→Z)" },
];

// Filter dropdown options. Group every session by event_id (skipping
// rows with no event_id), label "Event title (N sessions)", sort by
// session count desc so the busy events surface first.
const eventOptions = computed(() => {
  const groups = new Map();
  for (const session of sessions.value) {
    const eventId = String(session.eventId || "").trim();
    if (!eventId) continue;
    const existing = groups.get(eventId);
    if (existing) {
      existing.count += 1;
    } else {
      groups.set(eventId, {
        value: eventId,
        title: String(session.eventTitle || "").trim() || "Untitled event",
        count: 1,
      });
    }
  }
  return Array.from(groups.values())
    .sort((a, b) => b.count - a.count || a.title.localeCompare(b.title))
    .map((group) => ({
      value: group.value,
      label: `${group.title} (${group.count})`,
    }));
});

const displayedSessions = computed(() => {
  const query = searchQuery.value.trim().toLowerCase();
  const filter = eventFilter.value;

  let list = sessions.value.slice();

  if (filter) {
    list = list.filter((card) => String(card.eventId || "") === filter);
  }

  if (query) {
    list = list.filter((card) => {
      const haystack = [
        card.eventTitle,
        card.sessionName,
        card.generatedByName,
        card.generatedByEmail,
      ]
        .map((value) => String(value || "").toLowerCase())
        .join(" ");
      return haystack.includes(query);
    });
  }

  list.sort((a, b) => compareSessions(a, b, sortBy.value));
  return list;
});

function compareSessions(a, b, mode) {
  const safeStr = (v) => String(v || "");
  const safeIso = (v) => new Date(String(v || "")).getTime() || 0;
  const safeUnix = (v) => Number(v) || 0;
  switch (mode) {
    case "generatedAsc":
      return safeIso(a.generatedAtIso) - safeIso(b.generatedAtIso);
    case "sessionDateDesc":
      return safeUnix(b.startedAtUnix) - safeUnix(a.startedAtUnix);
    case "sessionDateAsc":
      return safeUnix(a.startedAtUnix) - safeUnix(b.startedAtUnix);
    case "eventAsc":
      return safeStr(a.eventTitle).localeCompare(safeStr(b.eventTitle));
    case "eventDesc":
      return safeStr(b.eventTitle).localeCompare(safeStr(a.eventTitle));
    case "generatorAsc":
      return safeStr(a.generatedByName || a.generatedByEmail).localeCompare(
        safeStr(b.generatedByName || b.generatedByEmail),
      );
    case "generatedDesc":
    default:
      return safeIso(b.generatedAtIso) - safeIso(a.generatedAtIso);
  }
}

// ── Card helpers ───────────────────────────────────────────────────────────
function hashString(input) {
  const text = String(input || "");
  let hash = 0;
  for (let i = 0; i < text.length; i += 1) {
    hash = (hash * 31 + text.charCodeAt(i)) | 0;
  }
  return Math.abs(hash);
}

function gradientFor(sessionId) {
  const hash = hashString(sessionId);
  const hueA = hash % 360;
  const hueB = (hash * 7 + 60) % 360;
  return `linear-gradient(135deg, hsl(${hueA}, 62%, 48%) 0%, hsl(${hueB}, 58%, 38%) 100%)`;
}

function coverImageUrl(card) {
  // Phase 4: real AI cover, generated from the Professional Smart
  // Recap. Falls back to the gradient placeholder when the row
  // doesn't have one yet (legacy rows + brand-new fetches whose
  // cover job hasn't completed). Adds a `?v=<iso>` cache-buster only
  // when we have a generated_at timestamp so subsequent regenerations
  // bypass the browser's max-age=86400 cache for this URL.
  if (!card?.hasCoverImage || !card?.sessionId) return "";
  return `/api/sessions/${card.sessionId}/cover.png`;
}

function initialsFor(label) {
  const cleaned = String(label || "").trim();
  if (!cleaned) return "—";
  const words = cleaned.split(/\s+/).slice(0, 2);
  return words.map((w) => w[0]).join("").toUpperCase();
}

function cardTitle(card) {
  // Phase 4 follow-up: prefer the event title. Sessions rarely have
  // their own name set — the user-meaningful label is the event the
  // session belongs to.
  return (
    String(card.eventTitle || "").trim() ||
    String(card.sessionName || "").trim() ||
    "Untitled session"
  );
}

function formattedDate(card) {
  return card.startedAtLabel || "—";
}

function generatedByLine(card) {
  const who =
    String(card.generatedByName || "").trim() ||
    String(card.generatedByEmail || "").trim() ||
    "Unknown user";
  const when = String(card.generatedAtLabel || "").trim();
  return when ? `Generated by ${who} · ${when}` : `Generated by ${who}`;
}

function openSession(sessionId) {
  router.push(`/single-analysis/${sessionId}/session-overview`);
}

async function refresh() {
  await loadWorkspaceSessions().catch(() => {});
}

const showEmptyAfterFilters = computed(
  () => hasAnySessions.value && displayedSessions.value.length === 0,
);

function clearFilters() {
  searchQuery.value = "";
  eventFilter.value = "";
}
</script>

